# Python Loops

# For loop
print("Numbers from 1 to 5:")

for i in range(1, 6):
    print(i)

# Loop through a list
fruits = ["Apple", "Banana", "Mango"]

print("\nFruits:")

for fruit in fruits:
    print(fruit)

# While loop
print("\nWhile loop:")

count = 1

while count <= 5:
    print(count)
    count += 1